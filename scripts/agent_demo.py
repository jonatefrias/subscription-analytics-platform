"""Reproducible trace of the MCP tools answering one business question.

Calls the same functions the MCP server exposes, in the order an analyst agent would, and
writes the calls and their real outputs to docs/agent_demo.md. Nothing in the trace is written
by hand; rerun after `dbt build` to refresh it.

Question: "What happened to churn after the July 2025 price increase?"
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))  # run as a script from anywhere

from semantic_agent.server import describe_metric, list_metrics, query_metrics, verify_number  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "docs" / "agent_demo.md"
MONTHS = "{{ TimeDimension('metric_time', 'month') }} between '2025-04-01' and '2025-10-01'"


def table(rows: list[dict], columns: list[str]) -> str:
    def fmt(column: str, v: str) -> str:
        if v in ("", None):
            return ""
        try:
            x = float(v)
        except ValueError:
            return v[:10]
        return f"{x:.1%}" if "rate" in column else f"{x:,.0f}"

    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(c, r[c]) for c in columns) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    parts = ["# Agent demo: governed metrics over MCP", ""]
    parts += [
        "Trace of the four MCP tools answering *What happened to churn after the July 2025 price increase?*",
        "Generated by `scripts/agent_demo.py` from the default dataset; every output below is real.",
        "",
    ]

    catalog = list_metrics()
    kinds = {}
    for m in catalog:
        kinds[m["kind"]] = kinds.get(m["kind"], 0) + 1
    parts += [
        "## 1. `list_metrics`",
        "",
        f"{len(catalog)} metrics: " + ", ".join(f"{n} {k}" for k, n in kinds.items()) + ".",
        "",
    ]

    parts += ["## 2. `describe_metric`", ""]
    for name in ("logo_churn_rate", "expansion_mrr"):
        d = describe_metric(name)
        extra = d.get("filter") or f"{d.get('numerator')} / {d.get('denominator')}"
        parts += [f"- **{name}** ({d['kind']}): {d['description']} Definition: `{extra}`."]
    parts += [""]

    monthly = query_metrics(
        ["opening_customers_metric", "churned_customers", "logo_churn_rate", "expansion_mrr", "churned_mrr"],
        group_by=["metric_time__month"],
        where=MONTHS,
        order_by=["metric_time__month"],
    )
    parts += ["## 3. `query_metrics`: the months around the increase", ""]
    parts += [
        table(
            monthly["rows"],
            [
                "metric_time__month",
                "opening_customers_metric",
                "churned_customers",
                "logo_churn_rate",
                "expansion_mrr",
                "churned_mrr",
            ],
        ),
        "",
    ]
    parts += [
        "<details><summary>SQL generated by MetricFlow</summary>",
        "",
        "```sql",
        monthly["sql"],
        "```",
        "",
        "</details>",
        "",
    ]

    by_market = query_metrics(
        ["logo_churn_rate"],
        group_by=["metric_time__month", "customer__market_code"],
        where="{{ TimeDimension('metric_time', 'month') }} in ('2025-05-01', '2025-08-01')",
        order_by=["customer__market_code", "metric_time__month"],
    )
    parts += ["## 4. `query_metrics`: before (May) vs after (August), by market", ""]
    parts += [table(by_market["rows"], ["customer__market_code", "metric_time__month", "logo_churn_rate"]), ""]

    parts += ["## 5. `verify_number`: the gate before reporting", ""]
    july = next(r for r in monthly["rows"] if r["metric_time__month"].startswith("2025-07"))
    august = next(r for r in monthly["rows"] if r["metric_time__month"].startswith("2025-08"))
    checks = [
        verify_number("expansion_mrr", "month", "2025-07-01", float(july["expansion_mrr"])),
        verify_number("logo_churn_rate", "month", "2025-08-01", float(august["logo_churn_rate"])),
        verify_number("mrr", "quarter", "2025-07-01", 3 * 141521.0),  # a summed snapshot: must be rejected
    ]
    parts += ["| metric | period | reported | status | independent path |", "|---|---|---|---|---|"]
    for c in checks:
        parts += [
            f"| {c['metric']} | {c['grain']} {c['period_start']} | {c['reported_value']:,.4f} | "
            f"**{c['status']}** | {c['independent_method']} |"
        ]
    parts += [
        "",
        "The third check is a deliberate mistake (three monthly MRR values added up for a quarter); "
        "the gate rejects it because MRR is a snapshot.",
        "",
    ]
    parts += [
        "## Try it in Claude Code",
        "",
        "Open the repo in Claude Code: `.mcp.json` registers the server. Then ask, for example:",
        "*Using the subscription-metrics tools, what happened to churn after the July 2025 price increase? "
        "Verify every number before you report it.*",
        "",
    ]
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
