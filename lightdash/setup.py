"""First-run setup of the local Lightdash instance, then deploy the project and its content.

Idempotent: run it again after changing the dbt project or the content files.
  1. Wait for the server started by docker compose.
  2. On a fresh instance, register a local admin with a generated password, create the
     organization and a personal access token. They are written to lightdash/.env (git-ignored).
  3. Deploy the dbt project (explores, MetricFlow metrics, Lightdash metrics) with the CLI.
  4. Upload the charts and dashboards kept as code in lightdash/content.

Usage (normally through `make lightdash`):  python lightdash/setup.py
"""

from __future__ import annotations

import http.cookiejar
import json
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
ENV_FILE = HERE / ".env"
CLI = str(HERE / "cli.sh")
PROJECT_NAME = "Matchday analytics"
ADMIN_EMAIL = "demo@matchday.example"  # must match the owner in lightdash/content


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        return {}
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {key: value for key, value in pairs}


def write_env(env: dict[str, str]) -> None:
    ENV_FILE.write_text("".join(f"{key}={value}\n" for key, value in env.items()))
    ENV_FILE.chmod(0o600)


class Api:
    def __init__(self, url: str, api_key: str | None = None):
        self.url = url.rstrip("/")
        self.api_key = api_key
        self.opener = urllib.request.build_opener(urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()))

    def call(self, method: str, path: str, body: dict | None = None) -> dict:
        headers = {"content-type": "application/json"}
        if self.api_key:
            headers["Authorization"] = f"ApiKey {self.api_key}"
        data = json.dumps(body).encode() if body is not None else None
        request = urllib.request.Request(f"{self.url}/api/v1{path}", data=data, headers=headers, method=method)
        with self.opener.open(request, timeout=60) as response:
            return json.loads(response.read()).get("results")


def wait_for_server(api: Api, timeout: int = 600) -> dict:
    deadline = time.time() + timeout
    while time.time() < deadline:
        try:
            health = api.call("GET", "/health")
            if health["healthy"]:
                return health
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            pass
        time.sleep(3)
    sys.exit("Lightdash did not become healthy in time. See: docker compose -f lightdash/docker-compose.yml logs")


def bootstrap(api: Api, env: dict[str, str]) -> None:
    """Create the admin, the organization and an access token on a fresh instance."""
    env["LIGHTDASH_ADMIN_EMAIL"] = ADMIN_EMAIL
    env["LIGHTDASH_ADMIN_PASSWORD"] = secrets.token_urlsafe(18)
    api.call(
        "POST",
        "/user",
        {"firstName": "Demo", "lastName": "Analyst", "email": ADMIN_EMAIL, "password": env["LIGHTDASH_ADMIN_PASSWORD"]},
    )
    write_env(env)  # keep the password even if a later step fails
    api.call("PUT", "/org", {"name": "Matchday"})
    api.call(
        "PATCH",
        "/user/me/complete",
        {
            "organizationName": "Matchday",
            "jobTitle": "Analytics engineer",
            "isMarketingOptedIn": False,
            "isTrackingAnonymized": True,
            "enableEmailDomainAccess": False,
        },
    )
    token = api.call(
        "POST",
        "/user/me/personal-access-tokens",
        {"description": "local CLI", "expiresAt": None, "autoGenerated": False},
    )
    env["LIGHTDASH_API_KEY"] = token["token"]
    write_env(env)


def cli(*args: str) -> None:
    subprocess.run([CLI, *args], check=True)


def main() -> None:
    env = read_env()
    env.setdefault("LIGHTDASH_URL", "http://localhost:8080")
    api = Api(env["LIGHTDASH_URL"])
    health = wait_for_server(api)

    if health["requiresOrgRegistration"]:
        bootstrap(api, env)
    elif "LIGHTDASH_API_KEY" not in env:
        sys.exit(f"The instance is already set up but {ENV_FILE} has no LIGHTDASH_API_KEY. Run `make lightdash-reset`.")
    api = Api(env["LIGHTDASH_URL"], env["LIGHTDASH_API_KEY"])

    dbt_args = ["--project-dir", ".", "--profiles-dir", ".", "--target", "lightdash", "--select", "tag:lightdash"]
    projects = {p["name"]: p["projectUuid"] for p in api.call("GET", "/org/projects")}
    if PROJECT_NAME in projects:
        env["LIGHTDASH_PROJECT"] = projects[PROJECT_NAME]
        write_env(env)
        cli("deploy", *dbt_args)
    else:
        env.pop("LIGHTDASH_PROJECT", None)
        write_env(env)
        cli("deploy", "--create", PROJECT_NAME, *dbt_args)
        projects = {p["name"]: p["projectUuid"] for p in api.call("GET", "/org/projects")}
        env["LIGHTDASH_PROJECT"] = projects[PROJECT_NAME]
        write_env(env)

    cli("upload", "--force", "--path", str(HERE / "content"), "--project", env["LIGHTDASH_PROJECT"])
    print(f"\nLightdash is ready: {env['LIGHTDASH_URL']}")
    print(f"Sign in as {env['LIGHTDASH_ADMIN_EMAIL']}; the password is in {ENV_FILE}")


if __name__ == "__main__":
    main()
